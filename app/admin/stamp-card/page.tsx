'use client'

import { useEffect, useState } from 'react'
import AdminShell from '@/components/AdminShell'
import { useAuth } from '@/lib/auth-context'
import { Stamp, Save, Trash2, Loader2, CheckCircle } from 'lucide-react'

type StampCard = {
  id: string
  goal: number
  reward_text: string
  earn_mode: 'qr' | 'manual'
  active: boolean
}

export default function StampCardPage() {
  const { authFetch } = useAuth()
  const [card, setCard] = useState<StampCard | null>(null)
  const [loading, setLoading] = useState(true)
  const [saving, setSaving] = useState(false)
  const [saved, setSaved] = useState(false)
  const [error, setError] = useState('')

  const [goal, setGoal] = useState('10')
  const [rewardText, setRewardText] = useState('')
  const [earnMode, setEarnMode] = useState<'qr' | 'manual'>('qr')

  async function load() {
    setLoading(true)
    const r = await authFetch('/api/admin/stamp-card')
    const d = await r.json()
    if (r.ok && d.stampCard) {
      setCard(d.stampCard)
      setGoal(String(d.stampCard.goal))
      setRewardText(d.stampCard.reward_text)
      setEarnMode(d.stampCard.earn_mode)
    }
    setLoading(false)
  }

  useEffect(() => { load() }, [])

  async function save() {
    setError(''); setSaved(false); setSaving(true)
    const r = await authFetch('/api/admin/stamp-card', {
      method: 'PUT',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ goal: Number(goal), reward_text: rewardText, earn_mode: earnMode }),
    })
    const d = await r.json()
    if (!r.ok) { setError(d.error || 'Failed to save'); setSaving(false); return }
    setCard(d.stampCard)
    setSaved(true)
    setSaving(false)
    setTimeout(() => setSaved(false), 3000)
  }

  async function deactivate() {
    if (!confirm('Deactivate the stamp card? Members will keep their progress.')) return
    await authFetch('/api/admin/stamp-card', { method: 'DELETE' })
    setCard(null)
    setGoal('10'); setRewardText(''); setEarnMode('qr')
  }

  return (
    <AdminShell>
      <div className="p-6 max-w-xl">
        <div className="flex items-center gap-3 mb-6">
          <div className="w-10 h-10 rounded-xl bg-violet-100 flex items-center justify-center">
            <Stamp size={20} className="text-violet-600" />
          </div>
          <div>
            <h1 className="text-xl font-bold text-gray-900">Stamp Card</h1>
            <p className="text-sm text-gray-400">Configure your loyalty stamp card</p>
          </div>
        </div>

        {loading ? (
          <div className="flex items-center justify-center h-40">
            <Loader2 size={24} className="animate-spin text-violet-400" />
          </div>
        ) : (
          <>
            {card && (
              <div className="bg-emerald-50 border border-emerald-200 rounded-2xl p-4 mb-6 flex items-start gap-3">
                <CheckCircle size={18} className="text-emerald-500 shrink-0 mt-0.5" />
                <div>
                  <p className="text-sm font-medium text-emerald-800">Stamp card is active</p>
                  <p className="text-xs text-emerald-600 mt-0.5">
                    {card.goal} stamps → {card.reward_text} · {card.earn_mode === 'qr' ? 'Via QR scan' : 'Manual by staff'}
                  </p>
                </div>
              </div>
            )}

            <div className="bg-white rounded-2xl border border-gray-100 p-6 space-y-5">
              {/* Earn Mode */}
              <div>
                <label className="text-sm font-medium text-gray-700 block mb-2">How stamps are earned</label>
                <div className="flex gap-2 bg-gray-50 p-1 rounded-xl">
                  {([['qr', 'QR Scan', 'Member scans a QR code generated by staff'], ['manual', 'Manual', 'Staff taps "Add Stamp" on POS screen']] as const).map(([val, label, desc]) => (
                    <button key={val} onClick={() => setEarnMode(val)}
                      className={'flex-1 py-2.5 px-3 rounded-lg text-left transition-colors ' +
                        (earnMode === val ? 'bg-white shadow-sm' : 'text-gray-400')}>
                      <p className={'text-xs font-medium ' + (earnMode === val ? 'text-gray-800' : '')}>{label}</p>
                      <p className="text-xs text-gray-400 mt-0.5 leading-snug">{desc}</p>
                    </button>
                  ))}
                </div>
              </div>

              {/* Goal */}
              <div>
                <label className="text-sm font-medium text-gray-700 block mb-1.5">Stamps needed to complete</label>
                <div className="flex items-center gap-3">
                  <input value={goal} onChange={e => setGoal(e.target.value.replace(/\D/g, ''))}
                    type="number" inputMode="numeric" min="2" max="50"
                    className="w-24 px-3 py-2.5 rounded-xl border border-gray-200 text-sm focus:outline-none focus:border-violet-300 text-center font-bold" />
                  <p className="text-sm text-gray-400">stamps per completed card</p>
                </div>
              </div>

              {/* Reward */}
              <div>
                <label className="text-sm font-medium text-gray-700 block mb-1.5">Reward when card is complete</label>
                <input value={rewardText} onChange={e => setRewardText(e.target.value)}
                  placeholder="e.g. Free drink, 10% off next purchase"
                  className="w-full px-3 py-2.5 rounded-xl border border-gray-200 text-sm focus:outline-none focus:border-violet-300" />
                <p className="text-xs text-gray-400 mt-1.5">This text appears on the voucher when the member completes the card</p>
              </div>

              {/* Preview */}
              {Number(goal) >= 2 && rewardText && (
                <div className="bg-gradient-to-br from-violet-50 to-purple-50 rounded-xl p-4 border border-violet-100">
                  <p className="text-xs font-medium text-violet-700 mb-2">Preview</p>
                  <div className="flex flex-wrap gap-1.5 mb-3">
                    {Array.from({ length: Math.min(Number(goal), 12) }).map((_, i) => (
                      <div key={i} className={'w-6 h-6 rounded-full border-2 ' +
                        (i < 3 ? 'bg-violet-500 border-violet-500' : 'border-violet-300')} />
                    ))}
                    {Number(goal) > 12 && <span className="text-xs text-violet-400 self-center">+{Number(goal) - 12}</span>}
                  </div>
                  <p className="text-xs text-violet-600">Complete all {goal} → <span className="font-medium">{rewardText}</span></p>
                </div>
              )}

              {error && <p className="text-sm text-red-500">{error}</p>}

              <div className="flex gap-3 pt-1">
                <button onClick={save}
                  disabled={saving || !rewardText.trim() || Number(goal) < 2}
                  className="flex-1 flex items-center justify-center gap-2 py-3 rounded-xl bg-violet-600 text-white text-sm font-medium disabled:opacity-50">
                  {saving ? <Loader2 size={16} className="animate-spin" /> : saved ? <CheckCircle size={16} /> : <Save size={16} />}
                  {saving ? 'Saving…' : saved ? 'Saved!' : card ? 'Update Stamp Card' : 'Activate Stamp Card'}
                </button>
                {card && (
                  <button onClick={deactivate}
                    className="px-4 py-3 rounded-xl border border-gray-200 text-gray-400 hover:text-red-400 hover:border-red-200 transition-colors">
                    <Trash2 size={16} />
                  </button>
                )}
              </div>
            </div>
          </>
        )}
      </div>
    </AdminShell>
  )
}
